'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

const call = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);

contextBridge.exposeInMainWorld('wasl', {
  state: call('state'),
  onState: (fn) => ipcRenderer.on('state', (_e, s) => fn(s)),
  pairStart: call('pair.start'),
  pairCancel: call('pair.cancel'),
  unpair: call('unpair'),
  pickFiles: call('files.pick'),
  sendFiles: call('files.send'),
  cancelTransfer: call('files.cancel'),
  openFile: call('files.open'),
  clearTransfers: call('files.clear'),
  sendClipboard: call('clip.send'),
  copy: call('clip.copy'),
  ring: call('ring'),
  dismiss: call('notif.dismiss'),
  clearNotifications: call('notif.clear'),
  action: call('notif.action'),
  setSettings: call('settings.set'),
  pickDir: call('settings.pickDir'),
  openUrl: call('open.url'),
  pathOf: (file) => webUtils.getPathForFile(file),
  media: call('media.cmd'),
  toggle: call('toggle'),
  volume: call('volume'),
  nav: call('nav'),
  callCmd: call('call.cmd'),
  dial: call('call.dial'),
  callLog: call('calllog'),
  contacts: call('contacts'),
  smsThreads: call('sms.threads'),
  smsOpen: call('sms.open'),
  smsClose: call('sms.close'),
  smsSend: call('sms.send'),
  clipCopy: call('clip.history.copy'),
  clipPin: call('clip.history.pin'),
  clipDelete: call('clip.history.delete'),
  clipClear: call('clip.history.clear'),
  mute: call('notif.mute'),
  updateCheck: call('update.check'),
  updateInstall: call('update.install'),
  mirrorStart: call('mirror.start'),
  mirrorStop: call('mirror.stop'),
  mirrorWifi: call('mirror.wifi'),
  mirrorPair: call('mirror.pair'),
  mirrorConnect: call('mirror.connect'),
  mirrorRefresh: call('mirror.refresh'),
  fsList: call('fs.list'),
  fsGet: call('fs.get'),
});
